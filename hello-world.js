let n1 = Math.floor(Math.random() * 7) + 1;

switch (n1) {
    case 1:
        console.log(n1)
        console.log("Domingo")
        break;
    case 2:
        console.log(n1)
        console.log("Segunda")
        break;
    case 3:
        console.log(n1)
        console.log("Terça")
        break;
    case 4:
        console.log(n1)
        console.log("Quarta")
        break;
    case 5:
        console.log(n1)
        console.log("Quinta")
        break;
    case 6:
        console.log(n1)
        console.log("Sexta")
        break;
    case 7:
        console.log(n1)
        console.log("Sabado")
        break;
    default:
        console.log("entrada invalida digite um numero entre 1 e 7")
}