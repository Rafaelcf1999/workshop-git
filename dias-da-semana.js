let numero = 4;

for (let i = 1; i <= 7; i++) {
    if (numero === i) {
        switch (i) {
            case 1:
                console.log("Domingo");
                break;
            case 2:
                console.log("Segunda-feira");
                break;
            case 3:
                console.log("Terça-feira");
                break;
            case 4:
                console.log("Quarta-feira");
                break;
            case 5:
                console.log("Quinta-feira");
                break;
            case 6:
                console.log("Sexta-feira");
                break;
            case 7:
                console.log("Sábado");
                break;
        }
    }
}